package com.codecrafthub.model;

import com.fasterxml.jackson.annotation.JsonIgnoreProperties;
import com.fasterxml.jackson.annotation.JsonPropertyOrder;
import com.fasterxml.jackson.annotation.JsonProperty;

/**
 * One course a developer wants to learn.
 *
 * The JSON uses snake_case names (target_date, created_at) while the Java
 * fields use camelCase. {@code @JsonProperty} tells Jackson how to translate.
 */
@JsonIgnoreProperties(ignoreUnknown = true) // extra fields in a request are simply ignored
@JsonPropertyOrder({"id", "name", "description", "target_date", "status", "created_at"}) // tidy JSON output
public class Course {

    private Integer id;               // generated by the server, starting from 1
    private String name;              // required
    private String description;       // required

    @JsonProperty("target_date")
    private String targetDate;        // required, format YYYY-MM-DD

    private String status;            // "Not Started", "In Progress" or "Completed"

    @JsonProperty("created_at")
    private String createdAt;         // generated by the server, "yyyy-MM-dd HH:mm:ss"

    // Jackson needs a no-argument constructor to build objects from JSON
    public Course() {}

    public Course(Integer id, String name, String description, String targetDate, String status, String createdAt) {
        this.id = id;
        this.name = name;
        this.description = description;
        this.targetDate = targetDate;
        this.status = status;
        this.createdAt = createdAt;
    }

    public Integer getId() { return id; }
    public void setId(Integer id) { this.id = id; }

    public String getName() { return name; }
    public void setName(String name) { this.name = name; }

    public String getDescription() { return description; }
    public void setDescription(String description) { this.description = description; }

    public String getTargetDate() { return targetDate; }
    public void setTargetDate(String targetDate) { this.targetDate = targetDate; }

    public String getStatus() { return status; }
    public void setStatus(String status) { this.status = status; }

    public String getCreatedAt() { return createdAt; }
    public void setCreatedAt(String createdAt) { this.createdAt = createdAt; }
}
